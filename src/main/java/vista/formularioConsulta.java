    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
    int numero = Integer.parseInt(txtNumero.getText());

    modelo.cuenta c = controlador.buscarCuenta(numero);

    if (c == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "No se encontró una cuenta con ese número.");

        lblNumero.setText("");
        lblNombre.setText("");
        lblFecha.setText("");
        lblSaldo.setText("");
        lblTipo.setText("");
        return;
    }

    lblNumero.setText(String.valueOf(c.getNumero()));
    lblNombre.setText(c.getNombreDueno());

    modelo.fecha f = c.getFechaApertura();

    lblFecha.setText(
            f.getDia() + "/" + f.getMes() + "/" + f.getAnio());

    lblSaldo.setText(String.valueOf(c.getSaldo()));

    if (c instanceof modelo.cuentaAhorros) {
        lblTipo.setText("Cuenta de ahorros");
    } else if (c instanceof modelo.cuentaCorriente) {
        lblTipo.setText("Cuenta corriente");
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingresa un número de cuenta válido.");
}
        
    }//GEN-LAST:event_jButton1ActionPerformed

