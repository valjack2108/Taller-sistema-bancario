    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
try {
    int numero = Integer.parseInt(txtNumero.getText().trim());
    double valor = Double.parseDouble(txtValor.getText().trim());

    if (valor <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "El valor debe ser mayor que cero.");
        return;
    }

    modelo.cuenta c = controlador.buscarCuenta(numero);

    if (c == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "No existe una cuenta con ese número.");
        return;
    }

    boolean retirado = controlador.retirar(numero, valor);

    if (retirado) {
        javax.swing.JOptionPane.showMessageDialog(
                this, """
                      Retiro realizado correctamente.
                      Saldo actual: """ + c.getSaldo());

        txtNumero.setText("");
        txtValor.setText("");
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Retiro rechazado. Verifica el saldo "
                + "o el cupo de sobregiro disponible.");
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingresa un número de cuenta y un valor válidos.");
}
    }//GEN-LAST:event_jButton1ActionPerformed

